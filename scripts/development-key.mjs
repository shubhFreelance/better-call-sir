import {readFileSync,appendFileSync,chmodSync} from 'node:fs';
import {randomBytes} from 'node:crypto';
import {parseEnv} from 'node:util';
const file=process.argv[2]||'.env',config=parseEnv(readFileSync(file,'utf8'));
if(config.APP_MODE!=='development'||config.NODE_ENV==='production')throw new Error('Key setup is restricted to local development configuration.');
const names=['MFA_ENCRYPTION_KEY','OTP_HASH_KEY'];
for(const name of names)if(config[name]&&!/^[A-Za-z0-9+/]{43}=$/.test(config[name]))throw new Error('Existing authentication key is invalid; do not replace credentials automatically.');
chmodSync(file,0o600);
for(const name of names)if(!config[name])appendFileSync(file,'\n'+name+'='+randomBytes(32).toString('base64')+'\n');
console.log('Local MFA and OTP keys configured. No key material is printed.');
